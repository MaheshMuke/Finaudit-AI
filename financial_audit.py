
import re
import json
from pathlib import Path

import pdfplumber

PDF = Path("finaudit_test/infosys_fy2025_26.pdf")
OUTPUT = Path("finaudit_output")
OUTPUT.mkdir(exist_ok=True)

# Actual PDF page numbers, confirmed from your extraction output.
PAGE_MAP = {
    "balance_sheet": 286,
    "income_statement": 288,
    "cash_flow_1": 295,
    "cash_flow_2": 296,
}

# Match financial numbers, including Indian comma grouping,
# negative values in parentheses, and reported dashes.
NUMBER_PATTERN = re.compile(
    r"\(?-?\d[\d,]*(?:\.\d+)?\)?|[–—-]"
)

METRICS = {
    "revenue": (288, "Revenue from operations"),
    "total_income": (288, "Total income"),
    "total_expenses": (288, "Total expenses"),
    "profit_before_tax": (288, "Profit before tax"),
    "profit_after_tax": (288, "Profit for the year"),
    "total_assets": (286, "Total assets"),
    "operating_cash_flow": (
        295, "Net cash generated by operating activities"
    ),
    "investing_cash_flow": (
        296, "Net cash generated / (used in) from investing activities"
    ),
    "financing_cash_flow": (
        296, "Net cash used in financing activities"
    ),
    "closing_cash": (
        296, "Cash and cash equivalents at the end of the period"
    ),
}


def parse_number(token):
    token = token.strip()

    if token in {"–", "—", "-"}:
        return None

    negative = token.startswith("(") and token.endswith(")")
    cleaned = token.replace(",", "").replace("(", "").replace(")", "")
    value = float(cleaned)

    return -value if negative else value


def normalize(text):
    return re.sub(r"\s+", " ", text).strip().lower()


def main():
    if not PDF.exists():
        raise FileNotFoundError(f"PDF not found: {PDF.resolve()}")

    page_text = {}

    with pdfplumber.open(PDF) as pdf:
        for page_number in set(PAGE_MAP.values()):
            page_text[page_number] = (
                pdf.pages[page_number - 1].extract_text() or ""
            )

    results = {}

    for metric, (page_number, label) in METRICS.items():
        lines = page_text[page_number].splitlines()
        matches = [
            line for line in lines
            if normalize(label) in normalize(line)
        ]

        if len(matches) != 1:
            results[metric] = {
                "status": "REVIEW_REQUIRED",
                "page": page_number,
                "matching_lines": matches,
            }
            continue

        line = matches[0]
        tokens = NUMBER_PATTERN.findall(line)

        if len(tokens) < 2:
            results[metric] = {
                "status": "REVIEW_REQUIRED",
                "page": page_number,
                "line": line,
            }
            continue

        current = parse_number(tokens[-2])
        previous = parse_number(tokens[-1])

        results[metric] = {
            "status": "EXTRACTED",
            "label": label,
            "page": page_number,
            "unit": "INR crore",
            "FY2026": current,
            "FY2025": previous,
            "source_line": line,
        }

    # Calculate metrics only when extraction was successful.
    def value(metric, year):
        item = results.get(metric, {})
        if item.get("status") != "EXTRACTED":
            return None
        return item.get(year)

    def change(metric):
        current = value(metric, "FY2026")
        previous = value(metric, "FY2025")

        if current is None or previous in (None, 0):
            return None

        return round((current - previous) / abs(previous) * 100, 2)

    revenue_growth = change("revenue")
    profit_growth = change("profit_after_tax")

    revenue_2026 = value("revenue", "FY2026")
    profit_2026 = value("profit_after_tax", "FY2026")
    operating_cf_2026 = value("operating_cash_flow", "FY2026")

    ratios = {
        "revenue_growth_percent": revenue_growth,
        "profit_growth_percent": profit_growth,
        "profit_margin_FY2026_percent": (
            round(profit_2026 / revenue_2026 * 100, 2)
            if profit_2026 is not None
            and revenue_2026 not in (None, 0)
            else None
        ),
        "operating_cash_flow_to_profit_FY2026": (
            round(operating_cf_2026 / profit_2026, 3)
            if operating_cf_2026 is not None
            and profit_2026 not in (None, 0)
            else None
        ),
    }

    audit = {
        "company": "Infosys Limited",
        "statement_scope": "Consolidated",
        "currency_unit": "INR crore",
        "source_pdf": str(PDF),
        "metrics": results,
        "calculated_metrics": ratios,
        "limitations": [
            "Text extraction is not independently verified.",
            "Ratios are analytical indicators, not proof of fraud.",
            "Review every source line and page before relying on results.",
        ],
    }

    output_file = OUTPUT / "financial_audit.json"
    output_file.write_text(
        json.dumps(audit, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("\n========== FINANCIAL AUDIT ==========")

    for metric, item in results.items():
        if item["status"] == "EXTRACTED":
            print(
                f"{metric}: FY2026={item['FY2026']}, "
                f"FY2025={item['FY2025']}, "
                f"source page={item['page']}"
            )
        else:
            print(f"{metric}: REVIEW REQUIRED -> {item}")

    print("\nCalculated metrics:")
    for name, result in ratios.items():
        print(f"{name}: {result}")

    print("\nSaved:", output_file.resolve())


if __name__ == "__main__":
    main()
