STATEMENT_MARKERS = {
    "income": ("statement of profit and loss", "statement of profit or loss"),
    "balance": ("balance sheet", "statement of financial position"),
    "cash": ("statement of cash flows", "cash flow statement"),
}


def parse_number(token: str) -> float | None:
    token = token.strip()
    if token in {"-", "–", "—"}:
        return None
    negative = token.startswith("(") and token.endswith(")")
    value = float(token.replace(",", "").replace("(", "").replace(")", ""))
    return -value if negative else value


def _normalize(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


def _statement_for(text: str) -> str | None:
    normalized = _normalize(text)
    for statement, markers in STATEMENT_MARKERS.items():
        if any(_normalize(marker) in normalized for marker in markers):
            return statement
    return None


def _basis_matches(text: str, basis: str) -> bool:
    normalized = _normalize(text)
    has_consolidated = "consolidated" in normalized
    has_standalone = "standalone" in normalized or "stand alone" in normalized
    if basis == "consolidated":
        return has_consolidated and not has_standalone
    return has_standalone and not has_consolidated


def _unit_scale(text: str) -> tuple[str, float, str]:
    normalized = text.lower().replace(",", " ")
    currency = None
    for currency_code, pattern in (
        ("USD", r"\b(usd|us\$|dollars?)\b"),
        ("EUR", r"\b(eur|€|euros?)\b"),
        ("GBP", r"\b(gbp|£|pounds?)\b"),
        ("JPY", r"\b(jpy|¥|yen)\b"),
    ):
        if re.search(pattern, normalized):
            currency = currency_code
            break
    if currency is None and re.search(
        r"\b(inr|rupees?|rs\.?)\b|₹|in\s+`\s*(crore|lakh|million|billion)",
        normalized,
    ):
        currency = "INR"

    if currency is None:
        return "reported units (unverified)", 1.0, "unknown"
    if re.search(r"\b(crore|crores|cr)\b", normalized):
        return f"{currency} crore", 1.0, currency
    if re.search(r"\b(million|millions)\b", normalized):
        return f"{currency} crore", 0.1, currency
    if re.search(r"\b(lakh|lakhs)\b", normalized):
        return f"{currency} crore", 0.01, currency
    if re.search(r"\b(billion|billions)\b", normalized):
        return f"{currency} crore", 100.0, currency
    if currency == "INR" and re.search(r"\b(rupees?|rs\.?)\b|₹", normalized):
        return "INR crore", 0.0000001, currency
    return "reported units (unverified)", 1.0, "unknown"


def _candidate_year_pairs(pages: list[tuple[int, str]]) -> list[tuple[int, int]]:
    pairs: list[tuple[int, int]] = []
    for _, text in pages:
        lines = text.splitlines()
        for index, line in enumerate(lines):
            if YEAR_HEADER_RE.search(line):
                header = " ".join(lines[index : index + 4])
                years = [int(y) for y in re.findall(r"\b(20\d{2})\b", header)]
                for i in range(len(years) - 1):
                    if years[i] > years[i + 1] and years[i] - years[i + 1] <= 2:
                        pairs.append((years[i], years[i + 1]))
                        break
    return pairs


def _page_text(page) -> str:
    positioned_lines = []
    for block in page.get_text("dict")["blocks"]:
        for line in block.get("lines", []):
            spans_text = []
            for span in line.get("spans", []):
                t = span.get("text", "")
                font = span.get("font", "").lower()
                # Indian annual reports frequently use custom fonts like ITFRupee
                # where the rupee symbol is mapped to characters like 'H', 'J', or '`'.
                if ("rupee" in font or "itf" in font) and t in {"H", "`", "J"}:
                    t = "INR"
                spans_text.append(t)
            text = "".join(spans_text).strip()
            if text:
                x, y = line["bbox"][:2]
                positioned_lines.append((y, x, text))
    rows: list[list[tuple[float, float, str]]] = []
    row_baselines: list[float] = []
    for y, x, text in sorted(positioned_lines):
        if row_baselines and abs(y - row_baselines[-1]) <= 1.5:
            rows[-1].append((y, x, text))
            row_baselines[-1] = sum(item[0] for item in rows[-1]) / len(rows[-1])
        else:
            rows.append([(y, x, text)])
            row_baselines.append(y)
    return "\n".join(
        " ".join(text for _, _, text in sorted(lines, key=lambda item: item[1]))
        for lines in rows
    )


def _extract_row_value(
    line: str, aliases: tuple[str, ...]
) -> tuple[str, float | None, float | None] | None:
    normalized = _normalize(line)
    for alias in aliases:
        normalized_alias = _normalize(alias)
        if normalized == normalized_alias or normalized.startswith(normalized_alias + " "):
            tokens = NUMBER_RE.findall(line)
            if len(tokens) < 2:
                return None
            return alias, parse_number(tokens[-2]), parse_number(tokens[-1])
    return None


def extract_pdf(
    path: str | Path, statement_basis: str = "consolidated"
) -> dict:
    path = Path(path)
    if statement_basis not in {"consolidated", "standalone"}:
        raise ValueError("Statement basis must be consolidated or standalone.")
    if not path.is_file():
        raise FileNotFoundError(f"PDF does not exist: {path}")
    with path.open("rb") as source:
        if source.read(5) != b"%PDF-":
            raise ValueError("Uploaded document is not a valid PDF file.")
    checksum = hashlib.sha256(path.read_bytes()).hexdigest()

    selected_pages: dict[str, list[tuple[int, str]]] = {
        key: [] for key in STATEMENT_MARKERS
    }
    try:
        document = fitz.open(path)
        page_texts = [
            (page_number, _page_text(page))
            for page_number, page in enumerate(document, start=1)
        ]
        document.close()
    except Exception:
        # Keep pdfplumber as a supported fallback for damaged/unsupported PDFs.
        with pdfplumber.open(path) as pdf:
            page_texts = [
                (page_number, page.extract_text() or "")
                for page_number, page in enumerate(pdf.pages, start=1)
            ]
    for page_number, text in page_texts:
            statement = _statement_for(text)
            if statement and _basis_matches(text, statement_basis):
                selected_pages[statement].append((page_number, text))

    all_pages = [page for pages in selected_pages.values() for page in pages]
    year_pairs = _candidate_year_pairs(all_pages)
    pair_counts = Counter(year_pairs)
    selected_pair = next(
        (
            pair
            for pair, _ in pair_counts.most_common()
            if pair[0] - pair[1] <= 2
        ),
        None,
    )
    if not selected_pair:
        raise ValueError(
            "Could not identify two adjacent reporting years from statement headers."
        )
    current_year, previous_year = selected_pair

    unit_markers = [
        _unit_scale("\n".join(text.splitlines()[:18])) for _, text in all_pages
    ]
    known_units = [marker for marker in unit_markers if marker[2] != "unknown"]
    if not known_units:
        unit, scale, currency = ("reported units (unverified)", 1.0, "unknown")
    else:
        unit_counts = Counter(known_units)
        unit, scale, currency = unit_counts.most_common(1)[0][0]
    extracted: list[dict] = []
    for metric_key, spec in METRICS.items():
        pages = selected_pages[spec["statement"]]
        matches = []
        for page_number, text in pages:
            for line in text.splitlines():
                result = _extract_row_value(line, spec["labels"])
                if result:
                    label, current, previous = result
                    matches.append((page_number, line.strip(), label, current, previous))
        if not matches:
            continue
        if len(matches) > 1:
            # Prefer the first matching row on the actual primary statement page.
            matches.sort(key=lambda item: item[0])
        page_number, excerpt, label, current, previous = matches[0]
        extracted.extend(
            [
                {
                    "financial_year": f"FY{current_year}",
                    "metric_key": metric_key,
                    "original_label": label,
                    "value": current * scale if current is not None else None,
                    "unit": unit,
                    "currency": currency,
                    "pdf_page_number": page_number,
                    "source_excerpt": excerpt,
                    "extraction_method": "statement-heading + labeled-row text extraction",
                    "extraction_confidence": 0.9 if len(matches) == 1 else 0.78,
                    "verification_status": "unverified",
                },
                {
                    "financial_year": f"FY{previous_year}",
                    "metric_key": metric_key,
                    "original_label": label,
                    "value": previous * scale if previous is not None else None,
                    "unit": unit,
                    "currency": currency,
                    "pdf_page_number": page_number,
                    "source_excerpt": excerpt,
                    "extraction_method": "statement-heading + labeled-row text extraction",
                    "extraction_confidence": 0.9 if len(matches) == 1 else 0.78,
                    "verification_status": "unverified",
                },
            ]
        )

    if not extracted:
        raise ValueError(
            "No supported financial statement rows were extracted. "
            "The PDF may be scanned, use an unsupported layout, or not match the selected basis."
        )
    return {
        "checksum": checksum,
        "financial_years": [f"FY{current_year}", f"FY{previous_year}"],
        "statement_basis": statement_basis,
        "unit": unit,
        "metrics": extracted,
        "warnings": [
            "Automated text extraction is not an audit; verify figures against the cited report pages.",
            "Only supported labels on identified financial statements are extracted.",
        ],
    }
