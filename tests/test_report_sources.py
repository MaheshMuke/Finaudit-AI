def test_report_discovery_api_returns_persistent_candidates(
    isolated_database, monkeypatch
):
    from fastapi.testclient import TestClient

    from finaudit import api

    def fake_discover(*args, **kwargs):
        return [candidate()], ["NSE unavailable."]

    monkeypatch.setattr("finaudit.service.discover_candidates", fake_discover)
    monkeypatch.setattr(
        api,
        "download_discovered_report",
        lambda discovery_id, candidate_id: {"report_id": "mock-report"},
    )
    with TestClient(api.app) as client:
        started = client.post(
            "/reports/discover",
            json={
                "company_id": "INFY",
                "financial_year": "FY2026",
                "statement_basis": "consolidated",
            },
        )
        assert started.status_code == 202
        discovery_id = started.json()["discovery_id"]
        status = client.get(f"/reports/discover/{discovery_id}")
        assert status.status_code == 200
        assert status.json()["status"] == "completed"
        candidate_id = status.json()["candidates"][0]["candidate_id"]
        request = client.post(
            f"/reports/discover/{discovery_id}/candidates/{candidate_id}/download"
        )
        assert request.status_code == 202


