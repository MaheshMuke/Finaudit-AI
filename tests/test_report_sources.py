def test_official_source_http_403_falls_back_to_alternative_sources(monkeypatch):
    company = Company(company_id="TCS", name="Tata Consultancy Services Limited", symbol="TCS")
    monkeypatch.delenv("OPENROUTER_API_KEY", raising=False)
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)

    class SelectiveSession:
        def get(self, url, **kwargs):
            if "tcs.com" in url or "bseindia.com" in url:
                return MockResponse(b"Forbidden", url, "text/html", status=403)
            if "nseindia.com/api/annual-reports" in url:
                json_payload = (
                    b'{"data":[{"companyName":"Tata Consultancy Services Limited",'
                    b'"fromYr":"2025","toYr":"2026",'
                    b'"broadcast_dttm":"15-MAY-2026 23:48:30",'
                    b'"fileName":"https://nsearchives.nseindia.com/annual_reports/tcs_2026.pdf"}]}'
                )
                return MockResponse(json_payload, url, "application/json", status=200)
            return MockResponse(b"Forbidden", url, "text/html", status=403)

    results, errors = discover_candidates(
        company,
        "FY2026",
        "consolidated",
        session=SelectiveSession(),
    )
    assert len(results) == 1
    assert results[0]["pdf_url"] == "https://nsearchives.nseindia.com/annual_reports/tcs_2026.pdf"
    assert results[0]["source_kind"] == "nse_corporate_disclosure"
    assert any("HTTP 403" in err for err in errors)


